package ejemplos;

public class MisOperaciones {

	public static void main(String[] args) {
		// Declaración e inicialización de variables
		int x=3, y=8;
		
		System.out.println("x="+x+" y="+y);
		
		// Operaciones
		x++;
		y--;
		System.out.println("x="+x+" y="+y);
		x+=y;
		System.out.println("x="+x+" y="+y);
		x-=3;
		y*=2;
		System.out.println("x="+x+" y="+y);

	}
}
