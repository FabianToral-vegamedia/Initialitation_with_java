package ejemplos;

public class Incremento2 {

	public static void main(String[] args) {
		int a=5;					// Declaro e inicializo la variable a
		System.out.println(a);		// Muestro el valor de a
		a++;						// Incremento el valor de a
		System.out.println(a);		// Muestro el valor de a
		++a;						// Incremento el valor de a
		System.out.println(a);		// Muestro el valor de a
		System.out.println(a++);	// Muestro el valor de a y después lo inremento 
		System.out.println(a);		// Muestro el valor de a
		System.out.println(++a);	// Inremento el valor de a y después lo muestro 

	}

}
