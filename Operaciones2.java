package ejemplos;

public class Operaciones2 {

	public static void main(String[] args) {
		/*
		 * int/int = int
		 * int/float = float
		 * float/int = float
		 */
		
		// Números enteros
		int a=5;
		System.out.println("El valor de a es: "+a);
		System.out.println("El doble de a es: "+(a*2));
		System.out.println("El tripe de a es: "+(a*3));
		System.out.println("La mitad de a es: "+(a/2));
		
		System.out.println();
		
		// Números enteros
		float b=5;
		System.out.println("El valor de a es: "+b);
		System.out.println("El doble de a es: "+(b*2));
		System.out.println("El tripe de a es: "+(b*3));
		System.out.println("La mitad de a es: "+(b/2));
		
	}
}
