package ejemplos;

public class Incremento {

	public static void main(String[] args) {
		// Ejemplo de operador incremental
		int a=1;
		a++;
		System.out.println(a);		// 2
		++a;
		System.out.println(a);		// 3
		System.out.println(++a);	// 4
		System.out.println(a++);	// 4
		System.out.println(a);		// 5
	}
}
